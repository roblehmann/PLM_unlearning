"""Test 0 (prerequisite) — put both arms' F_test on the SAME decontamination footing.

Every claim in this experiment is of the form "F_test is/is not regenerated by X". That
claim is only interpretable if F_test is homology-disjoint from F_train, and the two arms
did NOT arrive with the same disjointness:

  * mgnify  — source-aware split, 0 hits at -c0.8, residual partial-coverage homology at
              -c0.5 (~30% of F_test), accepted upstream as intrinsic family homology.
  * pfam    — the ORIGINAL split, which the later headroom post-mortem showed is heavily
              train-homologous (the majority of F_test has a >=0.50-identity train hit).

If we measured the train/test gap on the native splits, "small gap for Pfam" would be
predicted by leakage alone and the mechanism claim would be unfalsifiable. So this step
applies ONE criterion to BOTH arms and writes the surviving subset:

    F_test_decon      = F_test members with NO F_train hit at >=50% identity over
                        >=50% coverage (mmseqs -s 7.5, --cov-mode 0)  [primary]
    F_test_decon_c08  = same at >=80% coverage (the looser, upstream-accepted criterion)

Downstream scripts score on ``F_test_decon`` whenever it survives with enough sequences
(common.primary_test_key), and every artifact records which key was used.

    python experiments/4_footprint_vs_generator/t0_decontaminate.py

CPU only; needs the mmseqs2 module (slurm/env_setup.sh loads it).
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import common as C
from src.utils.io import read_fasta, write_fasta

CRITERIA = [("F_test_decon", 0.5), ("F_test_decon_c08", 0.8)]
MIN_SEQ_ID = 0.5


def parse_args():
    p = argparse.ArgumentParser(description=__doc__)
    C.arm_args(p)
    p.add_argument("--min-seq-id", type=float, default=MIN_SEQ_ID)
    p.add_argument("--sensitivity", type=float, default=7.5)
    p.add_argument("--threads", type=int, default=8)
    p.add_argument("--force", action="store_true", help="recompute even if outputs exist")
    return p.parse_args()


def _write_synthetic(records, path: Path) -> None:
    """Write ``records`` under synthetic ids q0,q1,... (their list index).

    mmseqs derives its own sequence id from the FASTA header, and that derivation is
    header-FORMAT dependent: for a UniProt ``tr|ACC|NAME`` header it keeps only the middle
    accession, whereas our ``read_fasta`` keeps the whole ``tr|ACC|NAME`` token. Matching
    the two by string then silently fails and NOTHING is filtered (the pfam arm's original
    failure mode). Sequential synthetic ids we control on both sides remove that ambiguity
    for every header format — pfam UniProt and mgnify ``<src>/<range>`` alike.
    """
    with open(path, "w") as fh:
        for i, r in enumerate(records):
            fh.write(f">q{i}\n{r.seq}\n")


def hits_against(query_records, target_records, cov: float, args, workdir: Path, tag: str) -> set:
    """Indices of query records with at least one target hit at >= min-seq-id and >= cov.

    Both sides are re-written under synthetic ids so the returned set indexes ``query_records``
    directly, independent of the original FASTA header format.
    """
    q = workdir / f"query_{tag}.fasta"
    t = workdir / f"target_{tag}.fasta"
    _write_synthetic(query_records, q)
    _write_synthetic(target_records, t)
    out = workdir / f"hits_{tag}.m8"
    tmp = workdir / f"tmp_{tag}"
    tmp.mkdir(parents=True, exist_ok=True)
    cmd = [
        "mmseqs", "easy-search", str(q), str(t), str(out), str(tmp),
        "--min-seq-id", str(args.min_seq_id), "-c", str(cov), "--cov-mode", "0",
        "-s", str(args.sensitivity), "-e", "1e-3", "--threads", str(args.threads),
        "--max-seqs", "300", "-v", "1",
    ]
    print("  $ " + " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)
    idx = set()
    with open(out) as fh:
        for line in fh:
            parts = line.split("\t")
            if parts and parts[0].startswith("q"):
                idx.add(int(parts[0][1:]))
    return idx


def main() -> int:
    args = parse_args()
    if shutil.which("mmseqs") is None:
        print("ERROR: mmseqs not on PATH (module load mmseqs2/14.7). Downstream scripts "
              "will fall back to the NATIVE F_test and record that fact.", file=sys.stderr)
        return 2

    summary = {}
    for key in args.arms:
        arm = C.get_arm(key)
        C.banner(f"T0 DECONTAMINATE — {arm.label}")
        splits = arm.data / "splits"
        f_test = read_fasta(splits / "F_test.fasta")
        f_train = read_fasta(splits / "F_train.fasta")
        print(f"  F_test={len(f_test)}  F_train={len(f_train)}", flush=True)

        rec = {"n_F_test": len(f_test), "n_F_train": len(f_train), "min_seq_id": args.min_seq_id,
               "sensitivity": args.sensitivity, "criteria": {}}
        with tempfile.TemporaryDirectory(prefix=f"decon_{key}_") as td:
            wd = Path(td)
            for name, cov in CRITERIA:
                out_fa = arm.results / f"{name}.fasta"
                if out_fa.exists() and not args.force:
                    print(f"  {name}: exists, skipping (use --force)", flush=True)
                    rec["criteria"][name] = {"coverage": cov, "n_kept": len(read_fasta(out_fa)),
                                             "recomputed": False}
                    continue
                hit = hits_against(f_test, f_train, cov, args, wd, tag=f"c{cov}")
                kept = [r for i, r in enumerate(f_test) if i not in hit]
                write_fasta(kept, out_fa)
                frac = len(hit) / max(len(f_test), 1)
                print(f"  {name}: coverage>={cov} -> {len(hit)} contaminated "
                      f"({frac:.1%}), {len(kept)} kept -> {out_fa}", flush=True)
                # Sanity: kept + contaminated must equal the input. Guards against exactly
                # the id-join failure that made the first pfam run keep everything.
                assert len(kept) + len(hit) == len(f_test), \
                    f"decon accounting broken: {len(kept)}+{len(hit)} != {len(f_test)}"
                rec["criteria"][name] = {
                    "coverage": cov, "n_contaminated": len(hit), "frac_contaminated": frac,
                    "n_kept": len(kept), "path": str(out_fa), "recomputed": True,
                }
        summary[key] = rec
        C.save_json(rec, arm.results / "t0_decontaminate.json")

    C.banner("T0 SUMMARY — identical criterion, both arms")
    print(f"{'arm':<10}{'n_F_test':>10}{'contaminated':>14}{'kept (primary)':>16}")
    for key, rec in summary.items():
        c = rec["criteria"].get("F_test_decon", {})
        print(f"{key:<10}{rec['n_F_test']:>10}{c.get('frac_contaminated', float('nan')):>13.1%}"
              f"{c.get('n_kept', 0):>16}")
    C.save_json(summary, C.RESULTS / "t0_decontaminate.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
